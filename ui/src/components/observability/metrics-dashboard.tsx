import { useMemo } from 'react'
import { useTranslation } from 'react-i18next'

import {
  usePrometheusQuery,
  usePrometheusRangeQuery,
} from '@/lib/api/prometheus'
import { Skeleton } from '@/components/ui/skeleton'

import { formatValue, toTimeSeries, ValueUnit } from './time-series'
import { TimeSeriesChart } from './time-series-chart'
import { TimeWindow } from './use-time-window'

export type MetricsScopeKind = 'cluster' | 'node' | 'namespace' | 'workload'
export type WorkloadKind = 'deployment' | 'statefulset' | 'daemonset'

export interface MetricsScope {
  kind: MetricsScopeKind
  node?: string
  namespace?: string
  workloadKind?: WorkloadKind
  workloadName?: string
}

interface ScopeSelectors {
  container: string
  pod: string
  group: string
  restarts: (window: string) => string
}

// Kubernetes builds generated name suffixes from this alphabet (no vowels,
// no 0/1/3), which keeps e.g. Deployment "web" from matching pod "web-cache-0".
const GENERATED = '[bcdfghjklmnpqrstvwxz2456789]'

// Pod names generated by each controller, used to match a workload's pods.
const POD_NAME_SUFFIX: Record<WorkloadKind, string> = {
  deployment: `-${GENERATED}{1,10}-${GENERATED}{5}`,
  statefulset: '-[0-9]+',
  daemonset: `-${GENERATED}{5}`,
}

// Escapes for a PromQL double-quoted string holding an RE2 pattern.
const escapeRegex = (value: string) =>
  value.replace(/[.*+?^${}()|[\]\\]/g, '\\\\$&')

function scopeSelectors(scope: MetricsScope): ScopeSelectors | null {
  const containerBase = 'container!="",image!=""'
  const restartsBy = (group: string, selector: string) => (window: string) =>
    `sum by (${group}) (increase(kube_pod_container_status_restarts_total{${selector}}[${window}]))`

  switch (scope.kind) {
    case 'cluster':
      return {
        container: containerBase,
        pod: 'pod!=""',
        group: 'namespace',
        restarts: restartsBy('namespace', ''),
      }
    case 'node': {
      if (!scope.node) return null
      const node = `node="${scope.node}"`
      return {
        container: `${containerBase},${node}`,
        pod: `pod!="",${node}`,
        group: 'namespace',
        // kube-state-metrics restarts carry no node label, so join through kube_pod_info.
        restarts: (window) =>
          `sum by (namespace) (increase(kube_pod_container_status_restarts_total[${window}]) * on (namespace, pod) group_left () max by (namespace, pod) (kube_pod_info{${node}}))`,
      }
    }
    case 'namespace': {
      if (!scope.namespace) return null
      const namespace = `namespace="${scope.namespace}"`
      return {
        container: `${containerBase},${namespace}`,
        pod: `pod!="",${namespace}`,
        group: 'pod',
        restarts: restartsBy('pod', namespace),
      }
    }
    case 'workload': {
      if (!scope.namespace || !scope.workloadKind || !scope.workloadName)
        return null
      const pods = `namespace="${scope.namespace}",pod=~"${escapeRegex(scope.workloadName)}${POD_NAME_SUFFIX[scope.workloadKind]}"`
      return {
        container: `${containerBase},${pods}`,
        pod: pods,
        group: 'pod',
        restarts: restartsBy('pod', pods),
      }
    }
  }
}

interface Panel {
  id: string
  unit: ValueUnit
  summary: 'sum' | 'max'
  expr: (selectors: ScopeSelectors) => string
}

const PANELS: Panel[] = [
  {
    id: 'cpu',
    unit: 'cores',
    summary: 'sum',
    expr: (s) =>
      `sum by (${s.group}) (rate(container_cpu_usage_seconds_total{${s.container}}[5m]))`,
  },
  {
    id: 'memory',
    unit: 'bytes',
    summary: 'sum',
    expr: (s) =>
      `sum by (${s.group}) (container_memory_working_set_bytes{${s.container}})`,
  },
  {
    id: 'networkIn',
    unit: 'bytesPerSecond',
    summary: 'sum',
    expr: (s) =>
      `sum by (${s.group}) (rate(container_network_receive_bytes_total{${s.pod}}[5m]))`,
  },
  {
    id: 'networkOut',
    unit: 'bytesPerSecond',
    summary: 'sum',
    expr: (s) =>
      `sum by (${s.group}) (rate(container_network_transmit_bytes_total{${s.pod}}[5m]))`,
  },
  {
    id: 'throttling',
    unit: 'percent',
    summary: 'max',
    expr: (s) =>
      `sum by (${s.group}) (rate(container_cpu_cfs_throttled_periods_total{${s.container}}[5m])) / sum by (${s.group}) (rate(container_cpu_cfs_periods_total{${s.container}}[5m]))`,
  },
  {
    id: 'restarts',
    unit: 'count',
    summary: 'sum',
    expr: (s) => s.restarts('15m'),
  },
]

const TOP_SERIES = 5

function DashboardPanel({
  panel,
  selectors,
  timeWindow,
}: {
  panel: Panel
  selectors: ScopeSelectors
  timeWindow: TimeWindow
}) {
  const { t } = useTranslation()
  const expr = panel.expr(selectors)
  const range = usePrometheusRangeQuery(`topk(${TOP_SERIES}, ${expr})`, {
    start: timeWindow.start,
    end: timeWindow.end,
    step: timeWindow.step,
  })
  const summary = usePrometheusQuery(`${panel.summary}(${expr})`, {
    time: timeWindow.end,
  })
  const series = useMemo(
    () => toTimeSeries(range.data, (metric) => metric[selectors.group] || '-'),
    [range.data, selectors.group]
  )
  const summaryValue =
    summary.data?.resultType === 'vector' && summary.data.result[0]?.value
      ? Number(summary.data.result[0].value[1])
      : NaN
  const format = (value: number) => formatValue(value, panel.unit)

  return (
    <section className="flex min-w-0 flex-col rounded-xl border bg-card">
      <header className="flex items-baseline gap-3 border-b px-4 py-3">
        <h2 className="text-sm font-semibold">
          {t(`observability.metrics.panels.${panel.id}`)}
        </h2>
        <span className="ml-auto font-semibold tabular-nums">
          {format(summaryValue)}
        </span>
      </header>
      <div className="px-2 py-3">
        {range.isLoading ? (
          <Skeleton className="h-[180px] w-full" />
        ) : range.error ? (
          <p className="flex h-[180px] items-center justify-center px-4 text-center text-sm text-destructive">
            {range.error.message}
          </p>
        ) : series.length === 0 ? (
          <p className="flex h-[180px] items-center justify-center text-sm text-muted-foreground">
            {t('observability.metrics.noData')}
          </p>
        ) : (
          <TimeSeriesChart series={series} formatValue={format} />
        )}
      </div>
    </section>
  )
}

export function MetricsDashboard({
  scope,
  timeWindow,
}: {
  scope: MetricsScope
  timeWindow: TimeWindow
}) {
  const { t } = useTranslation()
  const selectors = scopeSelectors(scope)
  if (!selectors) {
    return (
      <p className="rounded-xl border border-dashed p-10 text-center text-sm text-muted-foreground">
        {t('observability.metrics.chooseTarget')}
      </p>
    )
  }
  return (
    <div className="grid grid-cols-1 gap-4 @3xl/main:grid-cols-2 @6xl/main:grid-cols-3">
      {PANELS.map((panel) => (
        <DashboardPanel
          key={panel.id}
          panel={panel}
          selectors={selectors}
          timeWindow={timeWindow}
        />
      ))}
    </div>
  )
}
